 * Description: KSP annotation processor, scans @Route and generates IRoute impl
 * -----------------------------------------------------------------
 */

class RouteProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger
) : SymbolProcessor {

    private val routeMap = mutableMapOf<String, String>()
    private var generated = false
    private val generatedClassNames = mutableListOf<String>()

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val symbols = resolver.getSymbolsWithAnnotation(Route::class.qualifiedName!!)

        for (symbol in symbols) {
            if (symbol !is KSClassDeclaration) {
                logger.error("@Route can only be applied to classes", symbol)
                continue
            }

            val routeAnnotation = symbol.annotations.find {
                it.shortName.asString() == "Route"
            } ?: continue

            val path = routeAnnotation.arguments
                .find { it.name?.asString() == "path" }
                ?.value as? String ?: continue

            val exported = routeAnnotation.arguments
                .find { it.name?.asString() == "exported" }
                ?.value as? Boolean ?: true

            if (!exported) continue

            val className = symbol.qualifiedName?.asString() ?: continue

            if (routeMap.containsKey(path)) {
                continue
            }

            routeMap[path] = className
        }

        if (routeMap.isNotEmpty() && !generated) {
            generated = true
            val className = generateUniqueClassName()
            generateRouteLoaderClass(className)
            generateServiceLoaderFile(className)
        }

        return emptyList()
    }

    /**
     * Generate IRoute implementation class (Kotlin source)
     * This class will be discovered and loaded by DexFile scanning
     */
    private fun generateRouteLoaderClass(className: String) {
        val packageName = "com.victor.neuro.router.generated"

        try {
            val outputStream = codeGenerator.createNewFile(
                dependencies = Dependencies.ALL_FILES,
                packageName = packageName,
                fileName = className,
                extensionName = "kt"
            )

            outputStream.bufferedWriter().use { writer ->
                writer.write("package $packageName\n\n")
                writer.write("import com.victor.neuro.router.core.NeuroRouter\n")
                writer.write("import com.victor.neuro.router.core.plugin.IRoute\n\n")
                writer.write("/**\n")
                writer.write(" * Auto-generated by NRouter annotation processor (KSP).\n")
                writer.write(" * Do not modify manually.\n")
                writer.write(" */\n")
                writer.write("class $className : IRoute {\n")
                writer.write("    override fun register() {\n")

                routeMap.forEach { (path, targetClass) ->
                    writer.write("        NeuroRouter.instance.registerRoute(\"$path\", $targetClass::class.java)\n")
                }

                writer.write("    }\n")
                writer.write("}\n")
            }

            logger.info("NRouter: generated $packageName.$className with ${routeMap.size} routes")
            generatedClassNames.add("$packageName.$className")
        } catch (e: Exception) {
            logger.error("Failed to generate route loader: ${e.javaClass.simpleName}: ${e.message}")
        }
    }

    /**
     * Generate META-INF/services file for ServiceLoader discovery
     */
    private fun generateServiceLoaderFile(className: String) {
        val packageName = "com.victor.neuro.router.generated"
        val fqn = "$packageName.$className"
        try {
            val outputStream = codeGenerator.createNewFile(
                dependencies = Dependencies.ALL_FILES,
                packageName = "META-INF.services",
                fileName = "com.victor.neuro.router.core.plugin.IRoute",
                extensionName = ""
            )
            outputStream.bufferedWriter().use { writer ->
                writer.write(fqn)
                writer.newLine()
            }
            logger.info("NRouter: generated META-INF/services file for $fqn")
        } catch (e: Exception) {
            logger.error("Failed to generate META-INF/services: ${e.javaClass.simpleName}: ${e.message}")
        }
    }

    /**
     * Generate unique class name based on route paths (ensures no conflict between modules)
     */
    private fun generateUniqueClassName(): String {
        val combined = routeMap.keys.sorted().joinToString("|")
        val digest = MessageDigest.getInstance("SHA-256").digest(combined.toByteArray())
        val hex = StringBuilder()
        for (i in 0 until 4) {
            hex.append(String.format("%02x", digest[i]))
        }
        return "RouteLoader_$hex"
    }
}
