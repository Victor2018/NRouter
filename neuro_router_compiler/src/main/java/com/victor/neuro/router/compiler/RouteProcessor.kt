 * -----------------------------------------------------------------
 * File: RouteProcessor
 * Author: Victor
 * Date: 2022/9/19
 * Description: 注解处理器，编译时扫描 @Route 注解并生成 IRoute 实现类
 * -----------------------------------------------------------------
 */

@SupportedAnnotationTypes("com.victor.neuro.router.annotation.Route")
@SupportedSourceVersion(SourceVersion.RELEASE_8)
class RouteProcessor : AbstractProcessor() {

    private val routeMap = mutableMapOf<String, String>()

    override fun process(annotations: Set<TypeElement>, roundEnv: RoundEnvironment): Boolean {
        if (roundEnv.processingOver()) return false

        val elements = roundEnv.getElementsAnnotatedWith(Route::class.java)
        if (elements.isEmpty()) return false

        for (element in elements) {
            if (element !is TypeElement) {
                processingEnv.messager.printMessage(
                    Diagnostic.Kind.ERROR,
                    "@Route can only be applied to classes",
                    element
                )
                continue
            }

            val route = element.getAnnotation(Route::class.java)
            val className = element.qualifiedName.toString()
            val path = route.path

            if (routeMap.containsKey(path)) {
                processingEnv.messager.printMessage(
                    Diagnostic.Kind.WARNING,
                    "Duplicate route path: $path, already registered by ${routeMap[path]}"
                )
                continue
            }

            routeMap[path] = className
        }

        if (routeMap.isNotEmpty()) {
            generateRouteLoaderClass()
        }

        return true
    }

    /**
     * 生成 IRoute 实现类（Java 源码）
     * 该类会被 DexFile 扫描自动发现并加载，无需 META-INF 资源文件
     */
    private fun generateRouteLoaderClass() {
        val className = generateUniqueClassName()
        val packageName = "com.victor.neuro.router.generated"
        val fullClassName = "$packageName.$className"

        try {
            val javaFile = processingEnv.filer.createSourceFile(fullClassName)
            javaFile.openWriter().use { writer ->
                writer.write("package $packageName;\n\n")
                writer.write("import com.victor.neuro.router.core.NeuroRouter;\n")
                writer.write("import com.victor.neuro.router.core.plugin.IRoute;\n\n")
                writer.write("/**\n")
                writer.write(" * Auto-generated by NRouter annotation processor.\n")
                writer.write(" * Do not modify manually.\n")
                writer.write(" */\n")
                writer.write("public class $className implements IRoute {\n")
                writer.write("    @Override\n")
                writer.write("    public void register() {\n")

                routeMap.forEach { (path, targetClass) ->
                    writer.write("        NeuroRouter.getInstance().registerRoute(\"$path\", $targetClass.class);\n")
                }

                writer.write("    }\n")
                writer.write("}\n")
            }

            processingEnv.messager.printMessage(
                Diagnostic.Kind.NOTE,
                "NRouter: generated $fullClassName with ${routeMap.size} routes"
            )
        } catch (e: Exception) {
            processingEnv.messager.printMessage(
                Diagnostic.Kind.ERROR,
                "Failed to generate route loader: ${e.message}"
            )
        }
    }

    /**
     * 根据路由路径生成唯一的类名（确保不同模块不会冲突）
     */
    private fun generateUniqueClassName(): String {
        val combined = routeMap.keys.sorted().joinToString("|")
        val digest = MessageDigest.getInstance("SHA-256").digest(combined.toByteArray())
        val hex = StringBuilder()
        for (i in 0 until 4) {
            hex.append(String.format("%02x", digest[i]))
        }
        return "RouteLoader_$hex"
    }
}
